import mongoose from "mongoose";

// Simple User Schema for Login & Registration
const userSchema = new mongoose.Schema(
  {
    username: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      minlength: 3,
    },
    email: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      lowercase: true,
    },
    password: {
      type: String,
      required: true,
      minlength: 6,
    },
    role: {
      type: String,
      default: "Mission Operator",
    },
  },
  { timestamps: true }
);

const User = mongoose.model("User", userSchema);

export default User;
